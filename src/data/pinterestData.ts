export function getPinsByBoard(slug: string): PinterestPin[] {
  if (slug === 'all') return PINTEREST_PINS;
  return PINTEREST_PINS.filter(pin => pin.boardSlug === slug);
}

export function searchPins(query: string, boardSlug?: string): PinterestPin[] {
  let results = boardSlug && boardSlug !== 'all' ? getPinsByBoard(boardSlug) : PINTEREST_PINS;
  if (!query || !query.trim()) return results;
  const q = query.toLowerCase().trim();
  return results.filter(pin =>
    pin.title.toLowerCase().includes(q) ||
    pin.board.toLowerCase().includes(q) ||
    pin.description.toLowerCase().includes(q) ||
    pin.tags.some(tag => tag.toLowerCase().includes(q))
  );
}

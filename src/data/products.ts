export const USD_RATE = 0.00065;

export function formatPrice(amountNGN: number, currency: 'NGN' | 'USD'): string {
  if (currency === 'USD') {
    return `$${Math.round(amountNGN * USD_RATE).toLocaleString()}`;
  }
  return `₦${amountNGN.toLocaleString()}`;
}
